    private static final Map<String, WorldMapIcon> BY_NAME = new HashMap<>();

    static {
        for (WorldMapIcon icon : values()) {
            BY_NAME.put(icon.displayName.toLowerCase(), icon);
        }
    }

    private final String displayName;
    private final int elementId;
    private final int category;

    WorldMapIcon(String displayName, int elementId, int category) {
        this.displayName = displayName;
        this.elementId = elementId;
        this.category = category;
    }

    /**
     * Returns the exact display name as it appears on the world map.
     */
    public String displayName() { return displayName; }

    /**
     * Returns the canonical {@link WorldMapElement} id for this icon.
     * Use with {@code IconQuery.forElement(int)} to enumerate placements.
     */
    public int elementId() { return elementId; }

    /**
     * Returns the element category id, or {@code 0} if the element has no
     * explicit category in the cache.
     */
    public int category() { return category; }

    /**
     * Looks up an icon by its display name (case-insensitive).
     */
    public static WorldMapIcon fromName(String name) {
        return name == null ? null : BY_NAME.get(name.toLowerCase());
    }
